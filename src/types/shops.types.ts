import type {
  ShopAddressTypeValue,
  ShopContactTypeValue,
  ShopRelationTypeValue,
  ShopStatusValue,
  ShopTypeValue,
} from "@/constants/shops.constants";

/**
 * ISO-8601 date/time string.
 */
export type ShopDate = string;

/**
 * Shop contact information.
 *
 * A shop can have multiple contact methods.
 */
export interface IShopContact {
  /** Unique contact identifier. */
  contact_id: string;

  /** Contact method type. */
  type: ShopContactTypeValue;

  /** Contact value: phone number, email address, or WhatsApp number. */
  value: string;

  /** Whether this is the primary contact method. */
  is_primary: boolean;

  /** Optional contact label, e.g. Owner, Manager, Reception. */
  label?: string;

  /** Whether this contact method has been verified. */
  is_verified?: boolean;
}

/**
 * Shop address information.
 */
export interface IShopAddress {
  /** Unique address identifier. */
  address_id: string;

  /** Address classification. */
  type: ShopAddressTypeValue;

  /** Building, house, or shop number. */
  building?: string;

  /** Street or road name. */
  street?: string;

  /** Locality or neighborhood. */
  locality?: string;

  /** City or town. */
  city: string;

  /** District, if applicable. */
  district?: string;

  /** State or province. */
  state: string;

  /** Country name. */
  country: string;

  /** ISO 3166-1 alpha-2 country code, e.g. IN. */
  country_code?: string;

  /** Postal or ZIP code. */
  postal_code?: string;

  /** Additional address directions or landmarks. */
  landmark?: string;

  /** Whether this is the primary address. */
  is_primary: boolean;
}

/**
 * Geographic coordinates.
 */
export interface IShopLocation {
  /** Latitude, range: -90 to 90. */
  latitude: number;

  /** Longitude, range: -180 to 180. */
  longitude: number;

  /** Optional location accuracy in metres. */
  accuracy?: number;

  /** Timestamp when coordinates were captured. */
  captured_at?: ShopDate;
}

/**
 * Shop operating hours for one day.
 */
export interface IShopDayHours {
  /** Whether the shop operates on this day. */
  is_open: boolean;

  /** Opening time in 24-hour HH:mm format. */
  opens_at?: string;

  /** Closing time in 24-hour HH:mm format. */
  closes_at?: string;

  /** Whether the shop remains open throughout the day. */
  is_24_hours?: boolean;
}

/**
 * Shop weekly operating schedule.
 */
export interface IShopOperatingHours {
  monday?: IShopDayHours;
  tuesday?: IShopDayHours;
  wednesday?: IShopDayHours;
  thursday?: IShopDayHours;
  friday?: IShopDayHours;
  saturday?: IShopDayHours;
  sunday?: IShopDayHours;

  /** IANA timezone, e.g. Asia/Kolkata. */
  timezone?: string;
}

/**
 * Shop metadata.
 */
export interface IShopMetaData {
  /** Optional shop registration or business identification number. */
  registration_number?: string;

  /** Optional GST identification number. */
  gstin?: string;

  /** Shop website URL. */
  website?: string;

  /** Shop logo or profile image URI. */
  logo?: string;

  /** Optional additional images. */
  images?: string[];

  /** Tags used for searching and filtering. */
  tags?: string[];

  /** Optional custom attributes. */
  custom?: Record<string, unknown>;
}

/**
 * Shop details.
 *
 * Represents a locally maintained shop record.
 * It does not imply official merchant registration.
 */
export interface IShopDetails {
  /** Unique shop identifier. */
  shop_id: string;

  /** Shop display name. */
  name: string;

  /** Optional shop description. */
  description?: string;

  /** Shop classification. */
  type: ShopTypeValue;

  /** Shop lifecycle status. */
  status: ShopStatusValue;

  /** User's relationship with this shop. */
  relation: ShopRelationTypeValue;

  /** Contact methods. */
  contacts: IShopContact[];

  /** Shop addresses. */
  addresses: IShopAddress[];

  /** Optional geographic location. */
  location?: IShopLocation;

  /** Optional operating schedule. */
  operating_hours?: IShopOperatingHours;

  /** Additional shop metadata. */
  meta_data?: IShopMetaData;

  /** Date/time when the shop record was created. */
  created_at: ShopDate;

  /** Date/time when the shop record was last modified. */
  updated_at: ShopDate;

  /** Optional archival timestamp. */
  archived_at?: ShopDate;
}

/**
 * Input type for creating a shop.
 *
 * Shop ID and timestamps are generated by the application/repository.
 */
export type ICreateShopInput = Omit<
  IShopDetails,
  "shop_id" | "created_at" | "updated_at" | "archived_at"
>;

/**
 * Input type for updating a shop.
 */
export type IUpdateShopInput = Partial<
  Omit<IShopDetails, "shop_id" | "created_at">
>;

/**
 * Shop search and filtering parameters.
 */
export interface IShopQuery {
  /** Search by shop name, address, or contact information. */
  search?: string;

  /** Filter by shop classification. */
  type?: ShopTypeValue;

  /** Filter by lifecycle status. */
  status?: ShopStatusValue;

  /** Filter by relationship type. */
  relation?: ShopRelationTypeValue;

  /** Filter by city. */
  city?: string;

  /** Filter by district. */
  district?: string;

  /** Filter by tags. */
  tags?: string[];

  /** Pagination offset. */
  offset?: number;

  /** Maximum number of results. */
  limit?: number;

  /** Sorting preference. */
  sort_by?: "name_asc" | "name_desc" | "newest" | "oldest" | "nearest";
}
