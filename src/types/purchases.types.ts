import type {
  PurchaseActionValue,
  PurchaseStatusValue,
  PurchaseUnitValue,
} from "@/constants/purchases.constants";

/**
 * ISO-8601 date/time string.
 *
 * Use a consistent ISO string for persisted records.
 * Convert to Date objects only when performing date operations.
 */
export type PurchaseDate = string;

/**
 * Monetary value.
 *
 * Store persisted amounts using integer minor units wherever possible.
 * For INR, 100 minor units = ₹1.
 */
export type PurchaseMoney = {
  /** Amount in the smallest currency unit (e.g. paise). */
  amount_minor: number;

  /** ISO 4217 currency code. */
  currency: string;
};

/**
 * Purchase quantity information.
 */
export interface IPurchaseQuantity {
  /** Numeric quantity purchased. */
  value: number;

  /** Unit used to measure/package the product. */
  unit: PurchaseUnitValue;
}

/**
 * Purchase pricing information.
 */
export interface IPurchasePricing {
  /** Actual MRP per unit, expressed in minor currency units. */
  mrp_minor?: number;

  /** Actual price paid per unit, expressed in minor currency units. */
  unit_price_minor: number;

  /** Total amount paid for this purchase line, expressed in minor units. */
  total_price_minor: number;

  /** Currency used for all pricing fields in this object. */
  currency: string;

  /** Discount applied to this purchase line, if any. */
  discount_minor?: number;
}

/**
 * Purchase lifecycle information.
 */
export interface IPurchaseStatus {
  /** Current lifecycle state of the purchase. */
  state: PurchaseStatusValue;

  /** Optional explanation for cancellation, return, or other status changes. */
  notes?: string;

  /** Date when the current status was last updated. */
  updated_at?: PurchaseDate;
}

/**
 * Purchase record.
 *
 * Represents a planned or actual purchase record.
 * It is independent of shopping-list item state.
 */
export interface IPurchases {
  /** Unique purchase identifier. */
  purchase_id: string;

  /** Product identifier, if the product exists in the product catalogue. */
  product_id?: string;

  /** Optional purchase group identifier. */
  purchase_group_id?: string;

  /** Optional local shop identifier. */
  shop_id?: string;

  /** Product name snapshot at the time of purchase. */
  product_name: string;

  /** Quantity and measurement unit. */
  quantity: IPurchaseQuantity;

  /** Pricing details. */
  pricing: IPurchasePricing;

  /** Purchase lifecycle information. */
  status: IPurchaseStatus;

  /** Date/time associated with the purchase. */
  purchased_at: PurchaseDate;

  /** Optional additional purchase notes. */
  purchase_notes?: string;

  /** Record creation timestamp. */
  created_at: PurchaseDate;

  /** Last record update timestamp. */
  updated_at: PurchaseDate;
}

/**
 * Purchase group.
 *
 * Groups multiple purchase records together, for example:
 * - Monthly grocery purchase
 * - Weekly household shopping
 * - Festival shopping
 */
export interface IPurchaseGroup {
  /** Unique group identifier. */
  group_id: string;

  /** Group title. */
  title: string;

  /** Optional group description. */
  description?: string;

  /** Date/time when the group was created. */
  created_at: PurchaseDate;

  /** Last group update timestamp. */
  updated_at: PurchaseDate;

  /** Optional date associated with the group. */
  purchased_at?: PurchaseDate;
}

/**
 * Purchase action/activity record.
 *
 * Can be used later for activity history and audit tracking.
 */
export interface IPurchaseActivity {
  /** Unique activity identifier. */
  activity_id: string;

  /** Associated purchase identifier. */
  purchase_id: string;

  /** Action performed on the purchase. */
  action: PurchaseActionValue;

  /** Optional description of the action. */
  notes?: string;

  /** Timestamp of the action. */
  created_at: PurchaseDate;
}

/**
 * Input type for creating a purchase.
 *
 * Server/database-generated timestamps and identifiers may be omitted
 * when they are generated by the repository layer.
 */
export type ICreatePurchaseInput = Omit<
  IPurchases,
  "purchase_id" | "created_at" | "updated_at"
>;

/**
 * Input type for updating an existing purchase.
 */
export type IUpdatePurchaseInput = Partial<
  Omit<IPurchases, "purchase_id" | "created_at">
>;

/**
 * Input type for creating a purchase group.
 */
export type ICreatePurchaseGroupInput = Omit<
  IPurchaseGroup,
  "group_id" | "created_at" | "updated_at"
>;

/**
 * Input type for updating a purchase group.
 */
export type IUpdatePurchaseGroupInput = Partial<
  Omit<IPurchaseGroup, "group_id" | "created_at">
>;
