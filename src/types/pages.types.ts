import type {
  PageContentFormatValue,
  PageStatusValue,
  PageTypeValue,
  PageVisibilityValue,
} from "@/constants/pages.constants";

/**
 * ISO-8601 date/time string.
 */
export type PageDate = string;

/**
 * SEO robots configuration.
 *
 * Controls whether search engines should index and follow page links.
 */
export interface IPage_Robots {
  index: boolean;
  follow: boolean;

  /** Optional additional robots directives. */
  noarchive?: boolean;
  nosnippet?: boolean;
  noimageindex?: boolean;
}

/**
 * Open Graph metadata.
 *
 * Used when sharing a page on social platforms.
 */
export interface IPage_OpenGraph {
  title?: string;
  description?: string;
  type?: "website" | "article";
  url?: string;
  image?: string;
  image_alt?: string;
  site_name?: string;
  locale?: string;
}

/**
 * Twitter/X card metadata.
 */
export interface IPage_Twitter {
  card?: "summary" | "summary_large_image";
  title?: string;
  description?: string;
  image?: string;
  image_alt?: string;
  site?: string;
  creator?: string;
}

/**
 * SEO metadata.
 */
export interface IPage_SEO {
  /** Search engine title. */
  title?: string;

  /** Search engine description. */
  description?: string;

  /** Canonical page URL. */
  canonical_url?: string;

  /** Search keywords. */
  keywords?: string[];

  /** Robots indexing configuration. */
  robots?: IPage_Robots;

  /** Open Graph metadata. */
  open_graph?: IPage_OpenGraph;

  /** Twitter/X metadata. */
  twitter?: IPage_Twitter;
}

/**
 * General page metadata.
 *
 * Contains information that describes the page independently
 * of its actual content.
 */
export interface IPage_Meta_Data {
  /** Page category. */
  type: PageTypeValue;

  /** Page publication status. */
  status: PageStatusValue;

  /** Page access visibility. */
  visibility: PageVisibilityValue;

  /** Page locale, e.g. en, en-IN, hi, as. */
  locale: string;

  /** SEO configuration. */
  seo?: IPage_SEO;

  /** Optional page author or content owner. */
  author?: string;

  /** Optional page cover/thumbnail image. */
  featured_image?: string;

  /** Optional tags for internal organization. */
  tags?: string[];

  /** Optional custom metadata. */
  custom?: Record<string, unknown>;
}

/**
 * Application page.
 *
 * Represents a reusable content page such as:
 * Privacy Policy, Terms & Conditions, About Us, etc.
 */
export interface IPage {
  /** Unique page identifier. */
  page_id: string;

  /** Human-readable page title. */
  title: string;

  /** URL-friendly unique page identifier. */
  slug: string;

  /** Short page summary. */
  description: string;

  /** Page metadata and SEO information. */
  meta_data: IPage_Meta_Data;

  /** Actual page content. */
  content: string;

  /** Format used to interpret the content. */
  content_format: PageContentFormatValue;

  /** Date/time when the page was created. */
  created_at: PageDate;

  /** Date/time when the page was last modified. */
  updated_at: PageDate;

  /** Publication timestamp, if published. */
  published_at?: PageDate;
}

/**
 * Input type for creating a page.
 *
 * Page ID and timestamps are generated by the application/repository.
 */
export type ICreatePageInput = Omit<
  IPage,
  "page_id" | "created_at" | "updated_at" | "published_at"
>;

/**
 * Input type for updating a page.
 */
export type IUpdatePageInput = Partial<Omit<IPage, "page_id" | "created_at">>;

/**
 * Page query/filter parameters.
 */
export interface IPageQuery {
  /** Filter by page slug. */
  slug?: string;

  /** Filter by page category. */
  type?: PageTypeValue;

  /** Filter by publishing status. */
  status?: PageStatusValue;

  /** Filter by visibility. */
  visibility?: PageVisibilityValue;

  /** Filter by locale. */
  locale?: string;

  /** Search by title or description. */
  search?: string;

  /** Pagination offset. */
  offset?: number;

  /** Maximum number of results. */
  limit?: number;
}
