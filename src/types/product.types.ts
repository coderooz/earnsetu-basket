import type {
  ProductImageTypeValue,
  ProductStatusValue,
  ProductTypeValue,
  ProductUnitValue,
  ProductVisibilityValue,
} from "@/constants/product.constants";

/**
 * ISO-8601 date/time string.
 */
export type ProductDate = string;

/**
 * Product dimensions.
 *
 * All measurements must use the same documented unit system.
 */
export interface IProductDimensions {
  length?: number;
  width?: number;
  height?: number;
  unit?: "mm" | "cm" | "m" | "in";
}

/**
 * Product measurement information.
 *
 * Describes the standard quantity represented by one catalogue unit.
 */
export interface IProductMeasurement {
  value: number;
  unit: ProductUnitValue;
}

/**
 * Product pricing information.
 *
 * This represents catalogue-level reference pricing.
 * Actual transaction pricing belongs to purchase records.
 */
export interface IProductPricing {
  /** Reference retail price in minor currency units. */
  mrp_minor?: number;

  /** Optional reference selling price in minor currency units. */
  selling_price_minor?: number;

  /** ISO 4217 currency code. */
  currency: string;
}

/**
 * Product image information.
 */
export interface IProductImage {
  /** Image identifier. */
  image_id: string;

  /** Image resource URL or local asset URI. */
  uri: string;

  /** Image classification. */
  type: ProductImageTypeValue;

  /** Optional accessible image description. */
  alt?: string;

  /** Display ordering. */
  sort_order?: number;
}

/**
 * Product metadata.
 *
 * Stores descriptive information that does not belong
 * directly to the product's core identity.
 */
export interface IProduct_Meta_Data {
  /** Product brand or manufacturer. */
  brand?: string;

  /** Product category identifier. */
  category_id?: string;

  /** Product subcategory identifier. */
  subcategory_id?: string;

  /** Product SKU or internal stock-keeping identifier. */
  sku?: string;

  /** Barcode such as EAN, UPC, or another supported format. */
  barcode?: string;

  /** Product tags for searching and filtering. */
  tags?: string[];

  /** Product dimensions, if applicable. */
  dimensions?: IProductDimensions;

  /** Product-specific attributes, e.g. colour, flavour, material. */
  attributes?: Record<string, string | number | boolean>;

  /** Additional application-specific metadata. */
  custom?: Record<string, unknown>;
}

/**
 * Product catalogue entity.
 *
 * Describes a product independently of purchases, shops,
 * and shop-specific inventory.
 */
export interface IProduct {
  /** Unique product identifier. */
  product_id: string;

  /** Product display name. */
  title: string;

  /** URL-friendly product identifier. */
  slug: string;

  /** Product description. */
  description?: string;

  /** Product classification. */
  type: ProductTypeValue;

  /** Standard product measurement. */
  measurement?: IProductMeasurement;

  /** Reference catalogue pricing. */
  pricing?: IProductPricing;

  /** Product images. */
  images?: IProductImage[];

  /** Product metadata. */
  meta_data: IProduct_Meta_Data;

  /** Product lifecycle status. */
  status: ProductStatusValue;

  /** Product visibility. */
  visibility: ProductVisibilityValue;

  /** Product creation timestamp. */
  created_at: ProductDate;

  /** Last modification timestamp. */
  updated_at: ProductDate;

  /** Optional archival timestamp. */
  archived_at?: ProductDate;
}

/**
 * Input type for creating a product.
 *
 * ID and timestamps are generated by the application/repository.
 */
export type ICreateProductInput = Omit<
  IProduct,
  "product_id" | "created_at" | "updated_at" | "archived_at"
>;

/**
 * Input type for updating a product.
 */
export type IUpdateProductInput = Partial<
  Omit<IProduct, "product_id" | "created_at">
>;

/**
 * Product search and filtering parameters.
 */
export interface IProductQuery {
  /** Search by product name, description, SKU, or barcode. */
  search?: string;

  /** Filter by product type. */
  type?: ProductTypeValue;

  /** Filter by category. */
  category_id?: string;

  /** Filter by brand. */
  brand?: string;

  /** Filter by lifecycle status. */
  status?: ProductStatusValue;

  /** Filter by visibility. */
  visibility?: ProductVisibilityValue;

  /** Filter by tags. */
  tags?: string[];

  /** Pagination offset. */
  offset?: number;

  /** Maximum number of results. */
  limit?: number;

  /** Sorting preference. */
  sort_by?: "name_asc" | "name_desc" | "newest" | "oldest";
}
